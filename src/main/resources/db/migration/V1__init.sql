-- Initial schema, derived from the JPA entities as of commit 9614a86.
-- Enum columns carry CHECK constraints: adding a new enum value needs a new migration.

CREATE TABLE users (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       varchar(100) NOT NULL UNIQUE,
    password    varchar(255) NOT NULL,
    first_name  varchar(50)  NOT NULL,
    last_name   varchar(50)  NOT NULL,
    phone       varchar(20),
    role        varchar(20)  NOT NULL CHECK (role IN ('USER', 'ADMIN')),
    enabled     boolean      NOT NULL,
    created_at  timestamp(6) with time zone NOT NULL,
    updated_at  timestamp(6) with time zone
);

CREATE TABLE refresh_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL CONSTRAINT fk_refresh_tokens_user REFERENCES users (id),
    token_hash  varchar(64) NOT NULL UNIQUE,
    expiry_date timestamp(6) with time zone NOT NULL,
    revoked     boolean     NOT NULL
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE cities (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  varchar(50) NOT NULL UNIQUE
);

CREATE TABLE districts (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id  bigint      NOT NULL CONSTRAINT fk_districts_city REFERENCES cities (id),
    name     varchar(50) NOT NULL,
    UNIQUE (city_id, name)
);

CREATE TABLE brands (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  varchar(50) NOT NULL UNIQUE
);

CREATE TABLE vehicle_models (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id  bigint      NOT NULL CONSTRAINT fk_vehicle_models_brand REFERENCES brands (id),
    name      varchar(50) NOT NULL,
    UNIQUE (brand_id, name)
);

CREATE TABLE vehicle_series (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id  bigint      NOT NULL CONSTRAINT fk_vehicle_series_model REFERENCES vehicle_models (id),
    name      varchar(50) NOT NULL,
    UNIQUE (model_id, name)
);

CREATE TABLE listings (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint        NOT NULL CONSTRAINT fk_listings_user REFERENCES users (id),
    district_id  bigint        NOT NULL CONSTRAINT fk_listings_district REFERENCES districts (id),
    title        varchar(150)  NOT NULL,
    description  text,
    price        numeric(15, 2) NOT NULL,
    currency     varchar(3)    NOT NULL CHECK (currency IN ('TRY', 'USD', 'EUR')),
    status       varchar(20)   NOT NULL CHECK (status IN ('PENDING_APPROVAL', 'ACTIVE', 'PASSIVE', 'SOLD')),
    view_count   integer       NOT NULL,
    version      bigint        NOT NULL,
    created_at   timestamp(6) with time zone NOT NULL,
    updated_at   timestamp(6) with time zone
);
CREATE INDEX idx_listings_status_created_at ON listings (status, created_at);
CREATE INDEX idx_listings_price ON listings (price);
CREATE INDEX idx_listings_user ON listings (user_id);
CREATE INDEX idx_listings_district ON listings (district_id);

CREATE TABLE listing_images (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id     bigint       NOT NULL CONSTRAINT fk_listing_images_listing REFERENCES listings (id),
    url            varchar(500) NOT NULL,
    display_order  integer      NOT NULL,
    cover          boolean      NOT NULL
);
CREATE INDEX idx_listing_images_listing ON listing_images (listing_id);

CREATE TABLE vehicle_details (
    listing_id         bigint      PRIMARY KEY CONSTRAINT fk_vehicle_details_listing REFERENCES listings (id),
    series_id          bigint      NOT NULL CONSTRAINT fk_vehicle_details_series REFERENCES vehicle_series (id),
    model_year         integer     NOT NULL,
    kilometer          integer     NOT NULL,
    fuel_type          varchar(20) NOT NULL CHECK (fuel_type IN ('GASOLINE', 'DIESEL', 'LPG', 'HYBRID', 'ELECTRIC')),
    gear_type          varchar(20) NOT NULL CHECK (gear_type IN ('MANUAL', 'AUTOMATIC', 'SEMI_AUTOMATIC')),
    body_type          varchar(20) CHECK (body_type IN ('SEDAN', 'HATCHBACK', 'SUV', 'STATION_WAGON', 'COUPE', 'CABRIO', 'PICKUP', 'MPV')),
    traction           varchar(10) CHECK (traction IN ('FWD', 'RWD', 'AWD')),
    vehicle_condition  varchar(10) NOT NULL CHECK (vehicle_condition IN ('NEW', 'USED')),
    from_who           varchar(20) NOT NULL CHECK (from_who IN ('OWNER', 'GALLERY', 'AUTHORIZED_DEALER')),
    engine_capacity    integer,
    engine_power       integer,
    color              varchar(30),
    exchangeable       boolean     NOT NULL,
    has_damage_record  boolean     NOT NULL
);
CREATE INDEX idx_vehicle_details_series ON vehicle_details (series_id);
CREATE INDEX idx_vehicle_details_model_year ON vehicle_details (model_year);
CREATE INDEX idx_vehicle_details_kilometer ON vehicle_details (kilometer);
CREATE INDEX idx_vehicle_details_fuel_type ON vehicle_details (fuel_type);

CREATE TABLE favorites (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL CONSTRAINT fk_favorites_user REFERENCES users (id),
    -- Mirrors @OnDelete(CASCADE) on Favorite: hard-deleting a listing removes its favorites.
    listing_id  bigint NOT NULL CONSTRAINT fk_favorites_listing REFERENCES listings (id) ON DELETE CASCADE,
    created_at  timestamp(6) with time zone NOT NULL,
    updated_at  timestamp(6) with time zone,
    CONSTRAINT uk_favorites_user_listing UNIQUE (user_id, listing_id)
);
CREATE INDEX idx_favorites_listing ON favorites (listing_id);
