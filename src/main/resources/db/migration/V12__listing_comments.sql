-- Comments under a listing and the owner's one reply per comment (parent_id set); both wait for admin approval.
CREATE TABLE listing_comments (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Hard-deleting a listing removes its comments; attachments are released by the application before that.
    listing_id        bigint        NOT NULL CONSTRAINT fk_listing_comments_listing REFERENCES listings (id) ON DELETE CASCADE,
    author_id         bigint        NOT NULL CONSTRAINT fk_listing_comments_author REFERENCES users (id),
    parent_id         bigint        CONSTRAINT fk_listing_comments_parent REFERENCES listing_comments (id) ON DELETE CASCADE,
    body              varchar(2000) NOT NULL,
    status            varchar(20)   NOT NULL CHECK (status IN ('PENDING_APPROVAL', 'APPROVED', 'REJECTED')),
    rejection_reason  varchar(500),
    reviewed_by       bigint        CONSTRAINT fk_listing_comments_reviewed_by REFERENCES users (id),
    reviewed_at       timestamp(6) with time zone,
    -- Replies the owner has sent to this comment, rejected and deleted ones included
    reply_attempts    integer       NOT NULL,
    version           bigint        NOT NULL,
    created_at        timestamp(6) with time zone NOT NULL,
    updated_at        timestamp(6) with time zone,
    CONSTRAINT ck_listing_comments_rejection_reason CHECK ((status = 'REJECTED') = (rejection_reason IS NOT NULL)),
    CONSTRAINT ck_listing_comments_review
        CHECK ((status = 'PENDING_APPROVAL') = (reviewed_at IS NULL AND reviewed_by IS NULL)),
    CONSTRAINT ck_listing_comments_reply_attempts
        CHECK (reply_attempts >= 0 AND (parent_id IS NULL OR reply_attempts = 0))
);

-- At most one reply per comment that is waiting or published; a rejected reply leaves room for another attempt
CREATE UNIQUE INDEX uq_listing_comments_active_reply ON listing_comments (parent_id)
    WHERE status IN ('PENDING_APPROVAL', 'APPROVED');
CREATE INDEX idx_listing_comments_parent ON listing_comments (parent_id);
CREATE INDEX idx_listing_comments_listing_status ON listing_comments (listing_id, status, created_at);
CREATE INDEX idx_listing_comments_author_created_at ON listing_comments (author_id, created_at);
CREATE INDEX idx_listing_comments_status_created_at ON listing_comments (status, created_at);

-- Comments a user has sent per listing. Kept apart from the comments so deleting or rejecting one does not give
-- the slot back, and so a single conditional upsert enforces the limit under concurrent requests.
CREATE TABLE listing_comment_quotas (
    listing_id  bigint  NOT NULL CONSTRAINT fk_listing_comment_quotas_listing REFERENCES listings (id) ON DELETE CASCADE,
    user_id     bigint  NOT NULL CONSTRAINT fk_listing_comment_quotas_user REFERENCES users (id),
    used        integer NOT NULL CHECK (used > 0),
    PRIMARY KEY (listing_id, user_id)
);

-- Evidence files (photos, PDF reports) uploaded straight to object storage, like listing images:
-- PENDING (upload URL issued) -> UPLOADED (file checked) -> ATTACHED (part of a comment) -> DELETED (file to remove).
-- No cascade from comments: the row must outlive its comment until the stored file is removed.
CREATE TABLE comment_attachments (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id       bigint       NOT NULL CONSTRAINT fk_comment_attachments_owner REFERENCES users (id),
    comment_id     bigint       CONSTRAINT fk_comment_attachments_comment REFERENCES listing_comments (id),
    status         varchar(20)  NOT NULL CHECK (status IN ('PENDING', 'UPLOADED', 'ATTACHED', 'DELETED')),
    object_key     varchar(200) NOT NULL CONSTRAINT uq_comment_attachments_object_key UNIQUE,
    file_type      varchar(10)  NOT NULL CHECK (file_type IN ('JPEG', 'PNG', 'WEBP', 'PDF')),
    size_bytes     bigint       NOT NULL,
    display_order  integer,
    version        bigint       NOT NULL,
    created_at     timestamp(6) with time zone NOT NULL,
    updated_at     timestamp(6) with time zone,
    CONSTRAINT ck_comment_attachments_attached
        CHECK ((status = 'ATTACHED') = (comment_id IS NOT NULL AND display_order IS NOT NULL))
);

CREATE INDEX idx_comment_attachments_comment ON comment_attachments (comment_id);
CREATE INDEX idx_comment_attachments_owner_status ON comment_attachments (owner_id, status);
CREATE INDEX idx_comment_attachments_status_created_at ON comment_attachments (status, created_at);
