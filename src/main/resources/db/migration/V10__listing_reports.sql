-- Users report listings; an admin resolves all open reports of a listing at once (dismiss or take it down).
CREATE TABLE listing_reports (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Mirrors @OnDelete(CASCADE) on ListingReport: hard-deleting a listing removes its reports.
    listing_id   bigint        NOT NULL CONSTRAINT fk_listing_reports_listing REFERENCES listings (id) ON DELETE CASCADE,
    reporter_id  bigint        NOT NULL CONSTRAINT fk_listing_reports_reporter REFERENCES users (id),
    reason       varchar(30)   NOT NULL CHECK (reason IN ('FAKE_OR_MISLEADING', 'FRAUD_SUSPECTED', 'WRONG_INFO',
                                                          'INAPPROPRIATE_CONTENT', 'ALREADY_SOLD', 'OTHER')),
    description  varchar(1000),
    status       varchar(20)   NOT NULL CHECK (status IN ('OPEN', 'DISMISSED', 'ACTION_TAKEN')),
    resolved_by  bigint        CONSTRAINT fk_listing_reports_resolved_by REFERENCES users (id),
    resolved_at  timestamp(6) with time zone,
    created_at   timestamp(6) with time zone NOT NULL,
    updated_at   timestamp(6) with time zone,
    CONSTRAINT ck_listing_reports_resolution
        CHECK ((status = 'OPEN') = (resolved_at IS NULL AND resolved_by IS NULL))
);

-- One open report per user and listing; a user may report again after the previous one was resolved
CREATE UNIQUE INDEX uq_listing_reports_open_per_reporter ON listing_reports (listing_id, reporter_id) WHERE status = 'OPEN';
CREATE INDEX idx_listing_reports_status_listing ON listing_reports (status, listing_id);
